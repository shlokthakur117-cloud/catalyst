"use client";

import React, { useState } from "react";
import { claimElderInviteAction } from "@/app/actions/auth";
import { useAuth } from "@/contexts/auth-context";
import { KeyRound, CheckCircle2, AlertCircle, Loader2 } from "lucide-react";

interface ClaimInviteModalProps {
  isOpen: boolean;
  onClose: () => void;
  onSuccess?: () => void;
}

export function ClaimInviteModal({ isOpen, onClose, onSuccess }: ClaimInviteModalProps) {
  const { refreshLinkedElders } = useAuth();
  const [inviteCode, setInviteCode] = useState("");
  const [relationshipType, setRelationshipType] = useState("family");
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [success, setSuccess] = useState(false);

  if (!isOpen) return null;

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    setError(null);
    setLoading(true);

    try {
      const res = await claimElderInviteAction(inviteCode, relationshipType);
      if (res.success) {
        setSuccess(true);
        await refreshLinkedElders();
        setTimeout(() => {
          onClose();
          if (onSuccess) onSuccess();
        }, 1200);
      } else {
        setError(res.error || "Failed to claim invitation.");
      }
    } catch (err: any) {
      setError(err.message || "An unexpected error occurred.");
    } finally {
      setLoading(false);
    }
  };

  return (
    <div className="fixed inset-0 z-50 bg-slate-900/50 backdrop-blur-sm flex items-center justify-center p-4">
      <div className="bg-white rounded-2xl max-w-md w-full p-6 sm:p-8 shadow-2xl border border-slate-200">
        <div className="flex items-center gap-3 mb-4">
          <div className="w-12 h-12 rounded-xl bg-emerald-100 flex items-center justify-center text-emerald-700">
            <KeyRound className="w-6 h-6" />
          </div>
          <div>
            <h2 className="text-xl font-bold text-slate-900">Link to Elder Account</h2>
            <p className="text-xs text-slate-500">Enter the invitation code generated by the elder</p>
          </div>
        </div>

        {success ? (
          <div className="py-6 text-center space-y-3">
            <CheckCircle2 className="w-12 h-12 text-emerald-600 mx-auto animate-bounce" />
            <h3 className="text-lg font-bold text-slate-900">Successfully Linked!</h3>
            <p className="text-sm text-slate-600">You now have authorized access to coordinate care.</p>
          </div>
        ) : (
          <form onSubmit={handleSubmit} className="space-y-4">
            {error && (
              <div className="p-3.5 rounded-xl bg-red-50 border border-red-200 flex items-start gap-2.5 text-xs font-medium text-red-800">
                <AlertCircle className="w-4 h-4 text-red-600 flex-shrink-0 mt-0.5" />
                <span>{error}</span>
              </div>
            )}

            <div>
              <label htmlFor="code" className="block text-sm font-semibold text-slate-700 mb-1">
                Elder Invitation Code
              </label>
              <input
                id="code"
                type="text"
                required
                placeholder="e.g. CARE-8F2A-91K4"
                value={inviteCode}
                onChange={(e) => setInviteCode(e.target.value.toUpperCase())}
                className="w-full text-center tracking-widest uppercase font-mono text-lg rounded-xl border border-slate-300 px-4 py-3 text-slate-900 focus:border-emerald-600 focus:ring-2 focus:ring-emerald-600 focus:outline-none"
              />
              <p className="text-xs text-slate-500 mt-1">Codes expire after 48 hours and can only be used once.</p>
            </div>

            <div>
              <label htmlFor="relType" className="block text-sm font-semibold text-slate-700 mb-1">
                Your Relationship
              </label>
              <select
                id="relType"
                value={relationshipType}
                onChange={(e) => setRelationshipType(e.target.value)}
                className="w-full rounded-xl border border-slate-300 px-3.5 py-2.5 text-sm text-slate-900 focus:border-emerald-600 focus:ring-2 focus:ring-emerald-600 focus:outline-none"
              >
                <option value="family">Family Member (Son / Daughter / Spouse)</option>
                <option value="primary_caregiver">Primary Caregiver</option>
                <option value="nurse">Nurse / Healthcare Aide</option>
                <option value="physician">Physician</option>
              </select>
            </div>

            <div className="flex gap-3 pt-3">
              <button
                type="button"
                onClick={onClose}
                className="flex-1 py-3 px-4 rounded-xl border border-slate-300 text-sm font-semibold text-slate-700 hover:bg-slate-50"
              >
                Cancel
              </button>
              <button
                type="submit"
                disabled={loading || !inviteCode.trim()}
                className="flex-1 py-3 px-4 rounded-xl bg-emerald-600 hover:bg-emerald-700 text-sm font-bold text-white shadow-md disabled:opacity-50 flex items-center justify-center gap-2"
              >
                {loading ? <Loader2 className="w-4 h-4 animate-spin" /> : "Verify & Link"}
              </button>
            </div>
          </form>
        )}
      </div>
    </div>
  );
}
